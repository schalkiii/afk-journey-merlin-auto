LOG_NAME_MAP = {**TEMPLATE_CN, **ACTION_CN}


def display_name(name):
    """把日志里的拼音模板/动作名转成「中文(拼音)」，未收录的原样返回。

    传入的 name 可能带后缀（如 ``kuaisushengji(2)``），只翻译括号前的基名，
    后缀原样保留，避免破坏重试序号等信息。
    """
    text = str(name)
    base = text.split("(")[0]
    cn = LOG_NAME_MAP.get(base)
    if not cn:
        return text
    return f"{cn}({base}){text[len(base):]}"
